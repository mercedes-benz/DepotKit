import Foundation

/// A coder can be used to encode and decode values of a specific type.
///
/// Values can only be saved in a depot when they can be converted to and from `Data`.
/// When registering a key you have to provide the depot a *coder* that is capable of **encoding** and **decoding** values of that type.
///
/// *DepotKit* provides built-in coders as static factory methods on ``AnyCoder``:
/// - ``AnyCoder/json(_:)`` for `Codable` types (JSON format).
/// - ``AnyCoder/plist(_:)`` for `Codable` types (binary property list format).
/// - ``AnyCoder/data(_:)`` for types conforming to ``LosslessDataConvertible``.
///
/// These factories support dot-syntax wherever ``AnyCoder`` is expected:
///
/// ```swift
/// depot.register(key: Key.from("user" / "profile"), coder: .json())
/// depot.register(key: Key.from("user" / "avatar"), coder: .data())
/// ```
///
/// Implement a coder that can encode and decode structs generated by *SwiftProtobuf*:
///
/// ```swift
/// struct ProtoCoder: Coder {
///     func encode(_ value: ProtoModel) throws -> Data {
///         try value.serializedData()
///     }
///
///     func decode(_ data: Data) throws -> ProtoModel {
///         try ProtoModel(serializedData: data)
///     }
/// }
/// ```
public protocol Coder<Value>: Sendable {
    /// The type that can be encoded and decoded by the coder.
    associatedtype Value: Sendable

    /// Encode a value to data.
    ///
    /// - Parameters:
    ///   - value: The value to encode.
    ///
    /// - Returns: The encoded data for `value`.
    ///
    /// - Throws: If an error during encoding occurs.
    /// Which error is thrown depends on the concrete implementation of the protocol.
    func encode(_ value: Value) throws -> Data

    /// Decode the data to a value.
    ///
    /// - Parameters:
    ///   - data: The data to decode.
    ///
    /// - Returns: The decoded value for `data`.
    ///
    /// - Throws: If an error during decoding occurs.
    /// Which error is thrown depends on the concrete implementation of the protocol.
    func decode(_ data: Data) throws -> Value

    /// A short human-readable description of this coder, used for diagnostics
    /// (e.g. ``Depot/storageTree()``). Composition coders should include their
    /// inner coder's description to show the full chain.
    var coderDescription: String { get }
}

extension Coder {
    public var coderDescription: String {
        String(describing: type(of: self))
    }
}
